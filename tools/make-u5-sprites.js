/* =========================================================================
   U5 食物组实物图：beef / drumstick / noodles / soup / broccoli / bread
                    rice / fish / dinner / milkbox / drop / juice
   -------------------------------------------------------------------------
   食物类全是「一眼要认出来」的东西，构图要点：
     · 轮廓照简笔画，但内部必须有「它是什么」的线索：牛肉的大理石纹、
       鸡腿的骨头、面条的筷子、汤的热气、西兰花的花球……
     · 碗/盘/杯一律「容器先画、内容后画、最后压容器口沿」，
       否则内容会盖住容器边缘，看起来像一坨颜色浮在空中
     · 颜色 5~8：食物本色 2~3 档 + 容器 1~2 档，够用
   ========================================================================= */
const A = require('./artkit.js');
const C = A.C;

/* ---------------- beef 牛肉 ----------------
   简笔画：肉块 (18,38)→(30,26)→(62,26)→(78,34)→(82,56)→(68,72)→(34,72)→(20,58)
           + 骨头 (78,40)→(90,34)→(94,42)→(90,50)→(80,48) + 两条雪花纹 */
function beef() {
  const im = A.canvas();
  // ① 骨头先画，肉块后画盖住根部
  A.outlined(im, [[76, 38], [90, 33], [94, 42], [90, 51], [78, 50]], C.CREAM);
  A.circle(im, 92, 38, 4, C.CREAM_HI);
  A.circle(im, 92, 47, 4, C.CREAM_HI);
  // ② 肉块
  A.outlined(im, [[18, 38], [30, 26], [62, 26], [78, 34], [82, 56], [68, 72], [34, 72], [20, 58]], C.MEAT);
  A.poly(im, [[20, 38], [31, 27], [60, 27], [66, 34], [50, 40], [30, 46]], C.MEAT_L);      // 上表面受光
  A.poly(im, [[64, 58], [82, 56], [68, 72], [34, 72], [30, 64]], C.MEAT_D);                // 下缘背光
  // ③ 雪花纹（大理石纹）：牛肉最关键的识别点
  A.poly(im, [[34, 40], [46, 36], [56, 40], [48, 46], [38, 45]], C.CREAM);
  A.poly(im, [[54, 52], [66, 48], [72, 54], [62, 60], [52, 58]], C.CREAM);
  A.poly(im, [[34, 42], [43, 39], [44, 43], [36, 45]], C.CREAM_HI);
  A.line(im, 28, 58, 42, 54, C.CREAM, 1);
  A.line(im, 46, 62, 60, 66, C.CREAM, 1);
  return im;
}

